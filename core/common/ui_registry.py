def _view_key(callback):
    view = getattr(callback, 'view_class', None) or callback
    return f'{view.__module__}.{view.__name__}'


def get_ui_route_registry():
    routes = {}

    def collect(pattern, prefix=''):
        for child in getattr(pattern, 'url_patterns', []):
            if isinstance(child, URLPattern):
                if not child.name:
                    continue
                path = prefix + str(child.pattern)
                if path.startswith('admin/'):
                    continue
                view_key = _view_key(child.callback)
                routes[child.name] = {
                    'path': '/' + path.lstrip('/'),
                    'type': VIEW_UI_TYPES.get(view_key),
                    'view': view_key,
                }
            elif isinstance(child, URLResolver):
                collect(child, prefix + str(child.pattern))

    collect(get_resolver())
    return routes
